"""Builds packages/core/src/imagery/coverage-data.ts from Natural Earth.

Input: ne_10m_admin_0_map_units.geojson from
https://github.com/nvkelso/natural-earth-vector (geojson/), public domain
(https://www.naturalearthdata.com/about/terms-of-use/, read 7 Oct 2026).

Each national source gets its country polygon grown by SEA_M over water and
by LAND_M over neighbouring land, with estuaries closed, then simplified.
Border probes on 7 Oct 2026 found DGT Ortos2025 imagery 600 m into Spain at
8 of 8 points and PNOA 600 m into France at 6 of 6, so the land margin is safe
for the sources that win a border (the order in the registry decides
overlaps). Melilla is left out of
PNOA (Pleiades Neo, Airbus DS, not CC BY).

    python coverage.py <map_units.geojson> > ../../core/src/imagery/coverage-data.ts
Needs shapely 2.
"""
import json, math, sys
from shapely.geometry import shape, box, Polygon, MultiPolygon
from shapely.ops import unary_union

# Over water the margin is wide: a coastal area should stay on one source,
# and the national sources answer flat or white there (counted as no coverage).
SEA_M = 10000
LAND_M = 300
# Closing radius: fills estuaries and bays narrower than twice this, so a
# river mouth inside a country does not fall to another source.
CLOSE_M = 5000
TOL_DEG = 0.0015
MIN_PART_KM2 = 0.05

UNITS = {
    'portugal-mainland': ['PRX'],
    'spain': ['ESP'],
    'france-metropolitan': ['FXX'],
}
MELILLA = box(-3.1, 35.2, -2.8, 35.4)


def deg(m, lat):
    # Buffer in degrees, using the longitude scale so the margin is never short.
    return m / (111320 * math.cos(math.radians(lat)))


def parts(g):
    return list(g.geoms) if isinstance(g, MultiPolygon) else [g]


def main(path):
    fc = json.load(open(path, encoding='utf8'))
    units = {f['properties']['GU_A3']: shape(f['geometry']).buffer(0) for f in fc['features']}
    out = {}
    for name, codes in UNITS.items():
        own = unary_union([units[c] for c in codes])
        if name == 'spain':
            own = own.difference(MELILLA)
        lat = own.centroid.y
        others = unary_union([g for k, g in units.items() if k not in codes and g.intersects(own.buffer(0.2))])
        closed = own.buffer(deg(CLOSE_M, lat)).buffer(-deg(CLOSE_M, lat)).difference(others)
        sea = own.buffer(deg(SEA_M, lat)).difference(others)
        land = own.buffer(deg(LAND_M, lat)).intersection(others)
        grown = unary_union([own, closed, sea, land]).simplify(TOL_DEG, preserve_topology=True)
        keep = []
        for p in parts(grown):
            km2 = p.area * (111.32 ** 2) * math.cos(math.radians(p.centroid.y))
            if km2 >= MIN_PART_KM2:
                keep.append(Polygon(p.exterior))
        out[name] = keep
    print('// Generated by packages/cli/scripts/coverage.py from Natural Earth 1:10m admin 0')
    print('// map units (public domain). Do not edit by hand.')
    print('import type { Ring } from \'../types.js\';')
    print()
    for name, polys in out.items():
        const = name.upper().replace('-', '_')
        rings = []
        for p in polys:
            coords = [[round(x, 4), round(y, 4)] for x, y in p.exterior.coords[:-1]]
            rings.append(json.dumps(coords, separators=(',', ':')))
        n = sum(len(p.exterior.coords) - 1 for p in polys)
        print(f'/** {len(polys)} rings, {n} vertices. */')
        print(f'export const {const}: Ring[] = [')
        for r in rings:
            print(f'  {r},')
        print('];')
        print()


if __name__ == '__main__':
    main(sys.argv[1])
